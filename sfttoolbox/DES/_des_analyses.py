"""Analysis and visualisation utilities for discrete-event simulations.

This module provides tools for processing and visualising metrics generated by
discrete-event simulations. It supports both individual simulation runs and
collections of simulation replications.

The main interface is ``SimulationAnalyses``, which provides methods for:

* Converting resource usage events into cumulative resource usage data.
* Combining results from multiple simulation replications onto a common
  time index.
* Plotting resource usage for individual simulations.
* Summarising multiple replications using the median and 95% percentile
  interval.

Typical usage:
    >>> analysis = SimulationAnalyses(simulation)
    >>> doctors = analysis.create_resource_dataframe("doctor_used")
    >>> nurses = analysis.create_resource_dataframe("nurse_used")
    >>> analysis.plot_resource_usage(
    ...     [doctors, nurses],
    ...     labels=["Doctors", "Nurses"],
    ... )

For multiple simulation replications:
    >>> analysis = SimulationAnalyses(simulations)
    >>> doctors = analysis.create_resource_dataframe("doctor_used")
    >>> analysis.plot_resource_usage(
    ...     [doctors],
    ...     labels=["Doctors"],
    ... )

Classes:
    SimulationAnalyses: Analyse and visualise resource usage from one or more
        discrete-event simulation runs.
"""

__all__ = [
    "SimulationAnalyses",
]

import math

import pandas as pd
from matplotlib import pyplot as plt

import sfttoolbox


class SimulationAnalyses:
    """Analyse and visualise resource usage from simulation results.

    Supports analysis of either a single simulation or multiple simulation
    replications. When multiple replications are supplied, resource usage can
    be summarised across simulations using quantiles.

    Args:
        simulation_framework: A simulation framework instance or a list of
            simulation framework instances containing simulation metrics and
            environment information.

    Attributes:
        sf: The simulation framework instance or list of simulation framework
            instances being analysed.
        final_time_mins: Maximum simulation time in minutes.
        final_time: Maximum simulation time rounded up to whole hours.
    """

    def __init__(self, simulation_framework):
        """Initialise the simulation analysis.

        Args:
            simulation_framework: A simulation framework instance or a list of
                simulation framework instances. Each instance must have an
                ``env`` attribute containing the simulation time in ``env.now``.
        """
        self.sf = simulation_framework
        if isinstance(simulation_framework, list):
            self.final_time_mins = max([sf.env.now for sf in simulation_framework])
        else:
            self.final_time_mins = self.sf.env.now

        self.final_time = math.ceil(self.final_time_mins / 60)

    def create_resource_dataframe(self, col):
        """Create a dataframe containing cumulative resource usage.

        For a single simulation, returns the cumulative resource usage at each
        recorded event time. For multiple simulation replications, each
        simulation is reindexed to a common one-minute time interval and
        returned as a separate column.

        Args:
            col (str): Name of the resource metric to extract from the
                simulation metrics.

        Returns:
            pandas.DataFrame: Cumulative resource usage. For multiple
            simulations, rows represent simulation time in minutes and columns
            represent individual simulation replications.
        """
        if isinstance(self.sf, list):
            dfs = []
            for i, sf in enumerate(self.sf):
                df = self._create_resource_dataframe_single_sim(sf.metrics[col], col)
                df = (
                    df.set_index("Time")
                    .reindex(range(self.final_time_mins + 1))["cumsum"]
                    .ffill()
                    .fillna(0)
                    .to_frame(name=i)
                )
                dfs.append(df)
            res_used_df = pd.concat(dfs, axis=1)
        else:
            res_used_df = self._create_resource_dataframe_single_sim(
                self.sf.metrics[col], col
            )

        return res_used_df

    def _create_resource_dataframe_single_sim(self, metrics, col):
        """Create a cumulative resource usage dataframe for one simulation.

        Resource changes occurring at the same simulation time are summed
        before calculating cumulative usage. A zero-valued observation is
        added at time zero so that resource usage starts from zero.

        Args:
            metrics: Sequence of simulation metric records containing time and
                the corresponding change in resource usage.
            col (str): Name to assign to the resource usage column.

        Returns:
            pandas.DataFrame: Dataframe containing ``Time``, the resource
            usage change, and cumulative resource usage in ``cumsum``.
        """
        res_used_df = pd.DataFrame(metrics, columns=["Time", col])
        res_used_df = res_used_df.groupby("Time").agg("sum").reset_index()

        res_used_df["cumsum"] = res_used_df[col].cumsum()

        res_used_df.loc[-1] = [0, 0, 0]
        res_used_df.index += 1
        res_used_df = res_used_df.sort_index()

        return res_used_df

    def plot_resource_usage(self, dfs, labels=None, save_filename=None):
        """Plot cumulative resource usage over simulation time.

        For multiple simulation replications, plots the median resource usage
        with a shaded 95% interval between the 2.5th and 97.5th percentiles.
        For a single simulation, plots cumulative resource usage as a step
        function.

        Args:
            dfs (list[pandas.DataFrame]): Resource usage dataframes to plot,
                typically produced by ``create_resource_dataframe``.
            labels (list[str], optional): Labels for each resource shown in
                the plot. If not provided, labels are generated automatically
                as ``Resource 1``, ``Resource 2``, and so on.
            save_filename (str, optional): Filename, excluding the extension,
                to which the plot should be saved. If supplied, the figure is
                saved as a PNG at 600 DPI.

        Returns:
            matplotlib.figure.Figure: The generated matplotlib figure.
        """
        colors = [
            sfttoolbox.team_colours[c]["hex"] for c in sfttoolbox.team_colours.keys()
        ]

        if labels == None:
            labels = [f"Resource {i + 1}" for i in range(len(dfs))]

        if isinstance(self.sf, list):
            ax = (
                dfs[0]
                .quantile(0.5, axis=1)
                .plot(
                    figsize=(20, 10),
                    color=colors[0],
                    alpha=0.8,
                    linewidth=3,
                    label=labels[0],
                )
            )
            ax.fill_between(
                x=dfs[0].index,
                y1=dfs[0].quantile(0.025, axis=1),
                y2=dfs[0].quantile(0.975, axis=1),
                color=colors[0],
                alpha=0.2,
            )

            for i, df in enumerate(dfs[1:], 1):
                df.quantile(0.5, axis=1).plot(
                    ax=ax,
                    color=colors[i],
                    alpha=0.8,
                    linewidth=3,
                    label=labels[i],
                )
                ax.fill_between(
                    x=df.index,
                    y1=df.quantile(0.025, axis=1),
                    y2=df.quantile(0.975, axis=1),
                    color=colors[i],
                    alpha=0.2,
                )

        else:
            ax = (
                dfs[0]
                .set_index("Time")["cumsum"]
                .plot(
                    drawstyle="steps-post",
                    figsize=(20, 10),
                    label=labels[0],
                    color=colors[0],
                    alpha=0.8,
                    linewidth=3,
                )
            )

            for i, df in enumerate(dfs[1:], 1):
                df.set_index("Time")["cumsum"].plot(
                    drawstyle="steps-post",
                    ax=ax,
                    label=labels[i],
                    color=colors[i],
                    alpha=0.8,
                    linewidth=3,
                )

        ax.set_xlabel("Hour", fontsize=20)
        ax.set_ylabel("Resource Used", fontsize=20)
        ax.tick_params(axis="both", which="major", labelsize=18)

        ax.legend(fontsize=18)

        ax.set_xticks(
            [60 * i for i in range(self.final_time + 1)],
            [*range(self.final_time + 1)],
            rotation=90,
        )

        plt.tight_layout()

        fig = ax.get_figure()

        if save_filename:
            plt.savefig(f"{save_filename}.png", dpi=600)

        return fig
